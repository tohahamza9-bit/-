# -*- coding: utf-8 -*-
"""تعاقد البذرة ↔ حلّ الخزائن (بلاغ X1840).

لماذا هذا الملفّ موجود: انحرفت القاعدة الحيّة عن `SEED_TREASURIES` بأسماء مستعارة أُضيفت من
اللوحة، و`seed_if_empty` لا يعمل إلا على قاعدة **فارغة** — فالانحراف يتراكم بلا كاشف، وقاعدة
جديدة تُرجِع العطل. هذه الاختبارات تثبّت الحدّ في الاتجاهين على البذرة وحدها (نقيّة، بلا قاعدة):

  • الاسم الكامل غير الملتبس يُحلّ  ⇒ الحوالة تُكتب.
  • اسم المدينة عاريًا **لا** يُحلّ  ⇒ وجهةُ تسليم، تُصعَّد لقرار بشري.

الكاشف التشغيليّ لانحراف البذرة عن القاعدة الحيّة هو `tools/seed_drift.py` (لا يصلح اختبارًا:
السويت كلّها على mongomock ولا ترى قاعدةً حيّة).
"""
from __future__ import annotations

import pytest

from core.constants import SEED_TREASURIES
from core.models import TreasuryRecord
from core.parsing.resolve import resolve_treasury


def _seed() -> list[TreasuryRecord]:
    """سجلّات الخزائن كما يبذرها `seed_if_empty` حرفيًّا (active + aliases افتراضيّة)."""
    return [TreasuryRecord(**{"active": True, "aliases": [], **s}) for s in SEED_TREASURIES]


# ═══════════════════════════════════════════════════════════════════════════
# X1840 — الرموز التي أسقطت الحوالة
# ═══════════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("token", ["محمد حمامات", "محمد الحمامات", "محمد"])
def test_seed_resolves_full_treasury_name(token):
    """الاسم الكامل (بـ«ال» أو بدونها) يُحلّ إلى 79 — وإلّا سقطت الرسالة الثانية لـX1840.

    🔴 «محمد الحمامات» ليس زائدًا: `resolve_treasury` يطبّع بـ`normalize_ar` التي لا تُسقِط
       «ال» داخل النصّ، فلا يساوي الاسم «محمد حمامات» بلا alias صريح.
    """
    rec = resolve_treasury(token, _seed())
    assert rec is not None, f"«{token}» لم يُحلّ — تتكرّر خزينة X1840 الناقصة"
    assert rec.code == "79"


@pytest.mark.parametrize("token", ["الحمامات", "حمامات"])
def test_seed_rejects_bare_city_as_treasury(token):
    """مدينة وحدها ليست خزينة — وجهةُ تسليم (الذخيرة الذهبية A54، test_structural_treasury:42).

    كان alias عاريًا مضافًا يدويًّا في القاعدة الحيّة يجعلها تُحلّ إلى 79، فتخالف الذخيرة صامتةً.
    """
    assert resolve_treasury(token, _seed()) is None, \
        f"«{token}» صارت خزينة — مدينةٌ عاريةٌ تُخالف A54 وتُدخِل المال في حساب خاطئ"


def test_seed_treasury_79_identity_is_single():
    """«محمد حمامات» = 79 حصرًا — لا يمشي اسمٌ واحد بكودين (كان «61» سهوًا في تجهيزة اختبار)."""
    matches = [s for s in SEED_TREASURIES if s["name"] == "محمد حمامات"]
    assert len(matches) == 1
    assert matches[0]["code"] == "79"


