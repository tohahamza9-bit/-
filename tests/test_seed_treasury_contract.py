# فجوة معروفة (بند منفصل، غير مُصلَحة عمدًا) — جذر التطبيع
# ═══════════════════════════════════════════════════════════════════════════
# `resolve_treasury`/`_candidates` يطبّعان بـ`normalize_ar` التي تُبقي «ال» داخل النصّ، بينما
# `normalize_arabic_for_matching` تُسقِطها. فأيّ اسم مسجَّل يحوي «الـ» لا يُحلّ إن كتبه الموظّف
# بلا «ال» (والعكس). عولج هنا بـalias صريح للخزينة 79 فقط — **لا حلّ جذريّ**: توحيد التطبيع
# يمسّ المطابقة التامّة للخزائن **والموردين** معًا (`_candidates` مشترك)، ويُفسِد أسماءً حقيقيّة
# («شرع الله»→«شرع له»، «عز الدين»→«عز دين») ويُحدِث التباسًا جديدًا («البراق»→«براق»)،
# ويستلزم تعديل `_TN_CITIES` أيضًا. مُسجَّل بندًا منفصلًا.
@pytest.mark.parametrize("token", ["عمر عاصمة", "طلال عاصمة", "رحيم تونس عاصمة"])
def test_known_gap_al_prefix_variant_not_resolved(token):
    """يوثّق السلوك القائم: صيغة الاسم بلا «ال» لا تُحلّ. إن صار يُحلّ فقد نُفِّذ توحيد التطبيع
    — عندئذٍ احذف هذا الاختبار عمدًا لا بصمت، وراجع تصادم «براق» وفساد «شرع الله»."""
    assert resolve_treasury(token, _seed()) is None
